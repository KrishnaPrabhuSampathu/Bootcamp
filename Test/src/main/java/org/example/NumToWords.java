package org.example;

public class NumToWords {
    static void main() {
        //Declaring the value
        int num = 5;

        switch (num) {
            case 1: IO.println("One");
                break;
            case 2: IO.println("Two");
                break;
            case 3: IO.println("Three");
                break;
            case 4: IO.println("Four");
                break;
            case 5: IO.println("Five");
                break;
            case 6: IO.println("Six");
                break;
            case 7: IO.println("Seven");
                break;
            case 8: IO.println("Eight");
                break;
            case 9: IO.println("Nine");
                break;
            case 10: IO.println("Ten");
                break;
            default: IO.println("Invalid number");
        }
    }

}
